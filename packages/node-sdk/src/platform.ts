import type { GlobalFacade, GlobalPlatformFacade } from '@moonshot-ai/klient';

/**
 * Public platform-contract surface for the Node SDK.
 *
 * Runtime behavior is delegated to the canonical klient facade exposed by the
 * v2 harness. SDK hosts therefore use the same durable platform authority as
 * the CLI without inventing SDK-local shapes.
 */
export type KimiPlatformClient = GlobalPlatformFacade;

/** Return the canonical klient facade without introducing an SDK-local authority. */
export function createKimiPlatformClient(global: GlobalFacade): KimiPlatformClient {
  return global.platform;
}

